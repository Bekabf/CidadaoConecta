-- =====================================================
-- 01 - USUARIOS
-- =====================================================

CREATE TABLE CC2_USUARIO (
    ID_USUARIO NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    NOME VARCHAR2(120) NOT NULL,
    EMAIL VARCHAR2(180) NOT NULL,
    SENHA_HASH VARCHAR2(255) NOT NULL,

    PERFIL VARCHAR2(20)
        DEFAULT 'CIDADAO' NOT NULL,

    ATIVO NUMBER(1)
        DEFAULT 1 NOT NULL,

    DATA_CADASTRO TIMESTAMP
        DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT PK_CC2_USUARIO
        PRIMARY KEY (ID_USUARIO),

    CONSTRAINT UK_CC2_USUARIO_EMAIL
        UNIQUE (EMAIL),

    CONSTRAINT CK_CC2_USUARIO_PERFIL
        CHECK (PERFIL IN ('CIDADAO', 'GESTOR')),

    CONSTRAINT CK_CC2_USUARIO_ATIVO
        CHECK (ATIVO IN (0, 1))
);


-- =====================================================
-- 02 - CATEGORIAS
-- =====================================================

CREATE TABLE CC2_CATEGORIA (
