-- =====================================================
-- 03 - OCORRENCIAS URBANAS
-- =====================================================

CREATE TABLE CC2_OCORRENCIA (
    ID_OCORRENCIA NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    ID_USUARIO NUMBER,

    PROTOCOLO VARCHAR2(60) NOT NULL,
    ID_PUBLICO VARCHAR2(60) NOT NULL,

    TITULO VARCHAR2(160) NOT NULL,
    DESCRICAO CLOB NOT NULL,

    CIDADE VARCHAR2(120) NOT NULL,
    UF CHAR(2) NOT NULL,
    BAIRRO VARCHAR2(120) NOT NULL,
    RUA VARCHAR2(180) NOT NULL,
    NUMERO_ENDERECO VARCHAR2(30),
    PONTO_REFERENCIA VARCHAR2(300),

    STATUS VARCHAR2(25)
        DEFAULT 'ABERTA' NOT NULL,

    VISIBILIDADE_PUBLICA NUMBER(1)
        DEFAULT 0 NOT NULL,

    TITULO_PUBLICO VARCHAR2(160),
    RESUMO_PUBLICO VARCHAR2(500),

    DATA_CADASTRO TIMESTAMP
        DEFAULT LOCALTIMESTAMP NOT NULL,

    DATA_ATUALIZACAO TIMESTAMP
        DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT PK_CC2_OCORRENCIA
        PRIMARY KEY (ID_OCORRENCIA),

    CONSTRAINT FK_CC2_OCORRENCIA_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES CC2_USUARIO(ID_USUARIO),

    CONSTRAINT UK_CC2_OCORRENCIA_PROTOCOLO
        UNIQUE (PROTOCOLO),

    CONSTRAINT UK_CC2_OCORRENCIA_PUBLICO
        UNIQUE (ID_PUBLICO),

    CONSTRAINT CK_CC2_OCORRENCIA_STATUS
        CHECK (STATUS IN (
            'ABERTA',
            'EM_ANALISE',
            'EM_ANDAMENTO',
            'RESOLVIDA',
            'ENCERRADA'
        )),

    CONSTRAINT CK_CC2_OCORRENCIA_VISIB
        CHECK (VISIBILIDADE_PUBLICA IN (0, 1)),

    CONSTRAINT CK_CC2_OCORRENCIA_PUBLICACAO
        CHECK (
            VISIBILIDADE_PUBLICA = 0
            OR (
                TITULO_PUBLICO IS NOT NULL
                AND RESUMO_PUBLICO IS NOT NULL
            )
        ),

    CONSTRAINT CK_CC2_OCORRENCIA_UF
        CHECK (UF IN (
            'AC', 'AL', 'AP', 'AM', 'BA',
            'CE', 'DF', 'ES', 'GO', 'MA',
            'MT', 'MS', 'MG', 'PA', 'PB',
            'PR', 'PE', 'PI', 'RJ', 'RN',
            'RS', 'RO', 'RR', 'SC', 'SP',
            'SE', 'TO'
        ))
);


