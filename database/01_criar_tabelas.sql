-- =====================================================
-- 05 - HISTORICO DE STATUS
-- =====================================================

CREATE TABLE CC2_HISTORICO_STATUS (
    ID_HISTORICO NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    ID_OCORRENCIA NUMBER NOT NULL,
    ID_USUARIO NUMBER,

    STATUS_ANTERIOR VARCHAR2(25),
    STATUS_NOVO VARCHAR2(25) NOT NULL,
    TIPO_EVENTO VARCHAR2(25) NOT NULL,

    DESCRICAO VARCHAR2(1000) NOT NULL,

    DATA_ALTERACAO TIMESTAMP
        DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT PK_CC2_HISTORICO
        PRIMARY KEY (ID_HISTORICO),

    CONSTRAINT FK_CC2_HIST_OCORRENCIA
        FOREIGN KEY (ID_OCORRENCIA)
        REFERENCES CC2_OCORRENCIA(ID_OCORRENCIA),

    CONSTRAINT FK_CC2_HIST_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES CC2_USUARIO(ID_USUARIO),

    CONSTRAINT CK_CC2_HIST_STATUS_ANT
        CHECK (
            STATUS_ANTERIOR IS NULL
            OR STATUS_ANTERIOR IN (
                'ABERTA',
                'EM_ANALISE',
                'EM_ANDAMENTO',
                'RESOLVIDA',
                'ENCERRADA'
            )
        ),

    CONSTRAINT CK_CC2_HIST_STATUS_NOVO
        CHECK (
            STATUS_NOVO IN (
                'ABERTA',
                'EM_ANALISE',
                'EM_ANDAMENTO',
                'RESOLVIDA',
                'ENCERRADA'
            )
        ),

    CONSTRAINT CK_CC2_HIST_TIPO
        CHECK (
            TIPO_EVENTO IN (
                'CRIACAO',
                'ALTERACAO_STATUS',
                'OBSERVACAO'
            )
        ),

    CONSTRAINT CK_CC2_HIST_EVENTO
        CHECK (
            (
                TIPO_EVENTO = 'CRIACAO'
                AND STATUS_ANTERIOR IS NULL
                AND ID_USUARIO IS NULL
            )
            OR
            (
                TIPO_EVENTO = 'ALTERACAO_STATUS'
                AND STATUS_ANTERIOR IS NOT NULL
                AND STATUS_ANTERIOR <> STATUS_NOVO
                AND ID_USUARIO IS NOT NULL
            )
            OR
            (
                TIPO_EVENTO = 'OBSERVACAO'
                AND STATUS_ANTERIOR = STATUS_NOVO
            )
        )
);


