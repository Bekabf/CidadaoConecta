-- 07 - EVIDENCIAS FOTOGRAFICAS
-- =====================================================

CREATE TABLE CC2_EVIDENCIA (
    ID_EVIDENCIA NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    ID_OCORRENCIA NUMBER NOT NULL,

    NOME_ARQUIVO VARCHAR2(255) NOT NULL,
    TIPO_MIME VARCHAR2(30) NOT NULL,
    TAMANHO_BYTES NUMBER(12) NOT NULL,
    CAMINHO_ARQUIVO VARCHAR2(500) NOT NULL,

    DATA_ENVIO TIMESTAMP
        DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT PK_CC2_EVIDENCIA
        PRIMARY KEY (ID_EVIDENCIA),

    CONSTRAINT FK_CC2_EVIDENCIA_OCORRENCIA
        FOREIGN KEY (ID_OCORRENCIA)
        REFERENCES CC2_OCORRENCIA(ID_OCORRENCIA),

    CONSTRAINT CK_CC2_EVIDENCIA_TIPO
        CHECK (
            TIPO_MIME IN (
                'image/jpeg',
                'image/png',
                'image/webp'
            )
        ),

    CONSTRAINT CK_CC2_EVIDENCIA_TAMANHO
        CHECK (
            TAMANHO_BYTES > 0
            AND TAMANHO_BYTES <= 5242880
        )
);


