-- =====================================================
-- 09 - POSSIVEIS DUPLICIDADES
-- =====================================================

CREATE TABLE CC2_DUPLICIDADE (
    ID_DUPLICIDADE NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    ID_OCORRENCIA_A NUMBER NOT NULL,
    ID_OCORRENCIA_B NUMBER NOT NULL,

    PONTUACAO NUMBER(5,4) NOT NULL,

    STATUS_ANALISE VARCHAR2(20)
        DEFAULT 'SUGERIDA' NOT NULL,

    DATA_IDENTIFICACAO TIMESTAMP
        DEFAULT LOCALTIMESTAMP NOT NULL,

    CONSTRAINT PK_CC2_DUPLICIDADE
        PRIMARY KEY (ID_DUPLICIDADE),

    CONSTRAINT FK_CC2_DUPLICIDADE_A
        FOREIGN KEY (ID_OCORRENCIA_A)
        REFERENCES CC2_OCORRENCIA(ID_OCORRENCIA),

    CONSTRAINT FK_CC2_DUPLICIDADE_B
        FOREIGN KEY (ID_OCORRENCIA_B)
        REFERENCES CC2_OCORRENCIA(ID_OCORRENCIA),

    CONSTRAINT UK_CC2_DUPLICIDADE_PAR
        UNIQUE (
            ID_OCORRENCIA_A,
            ID_OCORRENCIA_B
        ),

    CONSTRAINT CK_CC2_DUPLICIDADE_ORDEM
        CHECK (
            ID_OCORRENCIA_A < ID_OCORRENCIA_B
        ),

    CONSTRAINT CK_CC2_DUPLICIDADE_PONT
        CHECK (
            PONTUACAO >= 0
            AND PONTUACAO <= 1
        ),

    CONSTRAINT CK_CC2_DUPLICIDADE_STATUS
        CHECK (
            STATUS_ANALISE IN (
                'SUGERIDA',
                'CONFIRMADA',
                'DESCARTADA'
            )
        )
);

